"""Audit whether the q286-WBSS full coefficient globally descends to four moduli.

The prior tail-support LP found that adding only modulus 130 to the dominant
support moduli 70, 154, and 286 closes the 24-row stress fixture.  This script
checks whether that was sample luck or an exact finite algebraic compression.
The stronger test is unit-level descent:

    the full q286-WBSS unit coefficient f(u) lies in the additive row span
    generated by total mass plus projections to moduli 70, 130, 154, and 286.

If this holds, then for every even target residue a modulo 10010 the reflected
orbit coefficient Phi_a({u,a-u})=(f(u)+f(a-u))/2 inherits the same additive
projection form.

If true, the four-modulus projection target is not just a renamed finite LP
patch.  It is still not a prime distribution theorem and does not prove
Goldbach; it only identifies the lower projection data that would determine
the full signed expectation.
"""

