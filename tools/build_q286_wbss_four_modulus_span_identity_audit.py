def source_commit():
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def json_ready(value):
    if isinstance(value, dict):
        return {str(key): json_ready(item) for key, item in value.items()}
    if isinstance(value, (tuple, list)):
        return [json_ready(item) for item in value]
    if isinstance(value, np.ndarray):
        return json_ready(value.tolist())
    if isinstance(value, np.generic):
        return json_ready(value.item())
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def projection_rowspace(orbits, moduli):
    matrices = [csr_matrix(np.ones((1, len(orbits)), dtype=np.float64))]
    row_counts = {"total_mass": 1}
    for modulus in moduli:
        residues = sorted({
            int(unit % modulus)
            for orbit in orbits
            for unit in orbit
        })
        residue_index = {residue: index for index, residue in enumerate(residues)}
        data = []
        row_indexes = []
        column_indexes = []
        for column, orbit in enumerate(orbits):
            scale = 1.0 / len(orbit)
            for unit in orbit:
                row_indexes.append(residue_index[int(unit % modulus)])
                column_indexes.append(column)
                data.append(scale)
        matrix = csr_matrix(
            (data, (row_indexes, column_indexes)),
            shape=(len(residues), len(orbits)),
            dtype=np.float64,
        )
        matrices.append(matrix)
        row_counts[str(modulus)] = len(residues)
    return vstack(matrices, format="csr"), row_counts


def coefficient_span_residual(phi, rowspace):
    solved = lsqr(rowspace.T, phi, atol=1e-12, btol=1e-12, iter_lim=2000)
    residual = phi - rowspace.T @ solved[0]
    scale = max(1.0, float(np.linalg.norm(phi)))
    return {
        "relative_l2_residual": float(np.linalg.norm(residual) / scale),
        "l2_residual": float(np.linalg.norm(residual)),
        "max_abs_residual": float(np.max(np.abs(residual))),
        "lsqr_iterations": int(solved[2]),
        "lsqr_stop_code": int(solved[1]),
        "lsqr_condition_estimate": float(solved[6]),
        "row_count": int(rowspace.shape[0]),
    }


def even_target_residues():
    return tuple(range(0, PERIOD, 2))


def build_unit_row(all_units, full_coefficients, principal):
    unit_columns = tuple((unit,) for unit in all_units)
    phi = np.asarray([
        full_coefficients[unit].real / principal
        for unit in all_units
    ], dtype=np.float64)
    family_rows = {}
    for family, moduli in MODULUS_FAMILIES.items():
        rowspace, row_counts = projection_rowspace(unit_columns, moduli)
        family_rows[family] = {
            "moduli": list(moduli),
            "projection_row_counts": row_counts,
            **coefficient_span_residual(phi, rowspace),
        }
    return {
        "unit_count": len(all_units),
        "coefficient_l2_norm": float(np.linalg.norm(phi)),
        "families": family_rows,
    }


def reflection_orbits(target_residue, units):
    unit_set = set(units)
    seen = set()
    orbits = []
    for unit in units:
        if unit in seen:
            continue
        reflected = (target_residue - unit) % PERIOD
        if reflected not in unit_set:
            raise AssertionError("reflection left admissible support")
        orbit = tuple(sorted({unit, reflected}))
        seen.update(orbit)
        orbits.append(orbit)
    return tuple(orbits)


def build_residue_row(target_residue, all_units, full_coefficients, principal):
    admissible_units = tuple(
        unit for unit in all_units
        if math.gcd((target_residue - unit) % PERIOD, PERIOD) == 1
    )
    orbits = reflection_orbits(target_residue, admissible_units)
    phi = np.asarray([
        math.fsum(
            (full_coefficients[unit].real / principal)
            for unit in orbit
        ) / len(orbit)
        for orbit in orbits
    ], dtype=np.float64)
    uniform = np.asarray(
        [len(orbit) / len(admissible_units) for orbit in orbits],
        dtype=np.float64,
    )
    family_rows = {}
    for family, moduli in MODULUS_FAMILIES.items():
        rowspace, row_counts = projection_rowspace(orbits, moduli)
        family_rows[family] = {
            "moduli": list(moduli),
            "projection_row_counts": row_counts,
            **coefficient_span_residual(phi, rowspace),
        }
    return {
        "target_residue": int(target_residue),
        "target_mod_286": int(target_residue % 286),
        "admissible_unit_count": len(admissible_units),
        "reflection_orbit_count": len(orbits),
        "uniform_full_action": float(np.dot(uniform, phi)),
        "coefficient_l2_norm": float(np.linalg.norm(phi)),
        "families": family_rows,
    }


def summarize_family(rows, family):
    family_rows = [row["families"][family] for row in rows]
    exact_rows = [
        row for row, family_row in zip(rows, family_rows)
        if family_row["relative_l2_residual"] <= TOLERANCE
    ]
    failures = [
        {
            "target_residue": row["target_residue"],
            "target_mod_286": row["target_mod_286"],
            "reflection_orbit_count": row["reflection_orbit_count"],
            "relative_l2_residual": family_row["relative_l2_residual"],
            "max_abs_residual": family_row["max_abs_residual"],
            "lsqr_stop_code": family_row["lsqr_stop_code"],
            "lsqr_iterations": family_row["lsqr_iterations"],
            "row_count": family_row["row_count"],
        }
        for row, family_row in zip(rows, family_rows)
        if family_row["relative_l2_residual"] > TOLERANCE
    ]
    worst_rows = sorted(
        (
            {
                "target_residue": row["target_residue"],
                "target_mod_286": row["target_mod_286"],
                "reflection_orbit_count": row["reflection_orbit_count"],
                "relative_l2_residual": family_row["relative_l2_residual"],
                "max_abs_residual": family_row["max_abs_residual"],
                "lsqr_stop_code": family_row["lsqr_stop_code"],
                "lsqr_iterations": family_row["lsqr_iterations"],
                "row_count": family_row["row_count"],
            }
            for row, family_row in zip(rows, family_rows)
        ),
        key=lambda item: (-item["relative_l2_residual"], item["target_residue"]),
    )[:12]
    return {
        "row_count": len(rows),
        "exact_span_count": len(exact_rows),
        "span_failure_count": len(failures),
        "maximum_relative_l2_residual": max(
            row["relative_l2_residual"] for row in family_rows),
        "maximum_max_abs_residual": max(
            row["max_abs_residual"] for row in family_rows),
        "relative_l2_residual_summary": finite_summary(
            row["relative_l2_residual"] for row in family_rows),
        "max_abs_residual_summary": finite_summary(
            row["max_abs_residual"] for row in family_rows),
        "lsqr_iteration_summary": finite_summary(
            row["lsqr_iterations"] for row in family_rows),
        "row_count_summary": finite_summary(
            row["row_count"] for row in family_rows),
        "first_failures": failures[:12],
        "worst_rows": worst_rows,
    }


